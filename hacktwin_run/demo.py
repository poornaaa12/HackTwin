#!/usr/bin/env python3
"""
demo.py

Reproducible end-to-end demonstration, from an empty database to a populated
dashboard:

  1. register every design in designs/ (HDL inspection, hashes, manifests)
  2. run the official conformance tests and the core benchmark suite on them
     in the real Hardware Simulator (with repeats)
  3. optionally run the GitHub workload programs as well
  4. train and evaluate the cycle predictor
  5. write reports/ and print the command that opens the dashboard

Usage:
    python demo.py                      # fresh data/demo.db, all internal designs, 2 repeats
    python demo.py --designs 1,jumpfold-8,multicycle-2phase --repeats 3
    python demo.py --with-workloads
    python demo.py --example            # rebuild the bundled example dataset (examples/example_twin.db)

Requires Java and the nand2tetris tools (see README). Without them, explore
the bundled example instead:  HACKTWIN_DB=examples/example_twin.db python app.py
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import time
from pathlib import Path

from hacktwin_config import BASE_DIR, DATA_DIR, simulator_cmd

EXAMPLE_DB = BASE_DIR / "examples" / "example_twin.db"


def main() -> None:
    ap = argparse.ArgumentParser(description="HackTwin end-to-end demo")
    ap.add_argument("--db", default=str(DATA_DIR / "demo.db"))
    ap.add_argument("--designs", default="1,2,3,alu-xor-negate,branch-table,multicycle-2phase,jumpfold-8,jumpfold-1")
    ap.add_argument("--repeats", type=int, default=2)
    ap.add_argument("--with-workloads", action="store_true", help="also run the 19 GitHub workload programs (1 repeat)")
    ap.add_argument("--keep", action="store_true", help="do not delete an existing database first")
    ap.add_argument("--example", action="store_true", help="build the small, labelled example dataset in examples/")
    ap.add_argument("--report-dir", default=None)
    args = ap.parse_args()

    if not Path(simulator_cmd()).exists() or not shutil.which("java"):
        sys.exit("The Hardware Simulator or Java was not found. Install them (README: Setup) or explore the bundled example:\n"
                 "  HACKTWIN_DB=examples/example_twin.db python3 app.py")
    db = Path(EXAMPLE_DB if args.example else args.db)
    if db.exists() and not args.keep:
        for suffix in ("", "-wal", "-shm"):
            Path(str(db) + suffix).unlink(missing_ok=True)
    db.parent.mkdir(parents=True, exist_ok=True)
    os.environ["HACKTWIN_DB"] = str(db)

    from cycle_predictor import train
    from experiment_runner import run_experiment
    from twin_store import TwinStore

    designs = [d.strip() for d in args.designs.split(",") if d.strip()]
    store = TwinStore(str(db))
    started = time.time()
    try:
        def progress(p):
            if p["done"] % 50 == 0 or p["done"] == p["total"]:
                print(f"  [{p['done']}/{p['total']}] {p['message']}", flush=True)
        print(f"1-2. Simulating {len(designs)} designs on the core suite ({args.repeats} repeats) -> {db}")
        s = run_experiment(store, designs, repeats=args.repeats, title="Demo: core suite", progress=progress)
        print(f"     {s['runs_attempted']} runs: {s['by_status']}; conformance {s['conformance']}")
        if args.with_workloads:
            print("3. Simulating the GitHub workload programs")
            s = run_experiment(store, designs, repeats=1, suites=("workloads",), conformance=False, title="Demo: GitHub workloads", progress=progress)
            print(f"     {s['runs_attempted']} runs: {s['by_status']}")
        print("4. Training and evaluating the cycle predictor")
        try:
            rep = train(store, model_file=db.parent / f"{db.stem}_models" / "cycle_predictor.joblib",
                        report_file=db.parent / f"{db.stem}_models" / "cycle_predictor_report.json")
            print("     macro MAE: " + ", ".join(f"{k}={v['mae']:.1f}" for k, v in rep["evaluation"]["macro_average"].items()))
        except ValueError as exc:
            print(f"     skipped: {exc}")
        if args.example:
            store.set_meta("dataset_label", {
                "kind": "example",
                "text": f"Bundled example dataset generated by demo.py --example on {time.strftime('%Y-%m-%d')} "
                        f"(real simulator runs of {len(designs)} HackTwin designs; no GitHub imports). It is separate from data/hacktwin.db.",
            })
    finally:
        store.close()
    if not args.example or args.report_dir:
        import generate_report
        sys.argv = ["generate_report.py", "--db", str(db), "--out", args.report_dir or str(BASE_DIR / "reports" / "demo")]
        generate_report.main()
    print(f"\nDone in {time.time() - started:.0f}s. Open the dashboard with:\n  HACKTWIN_DB=\"{db}\" python3 app.py --port 8080\n  then http://127.0.0.1:8080")


if __name__ == "__main__":
    main()
